import assert from "node:assert/strict";
import { JSDOM } from "./ui-check/node_modules/jsdom/lib/api.js";
const dom = new JSDOM('<!doctype html><html><body><div id="root"></div></body></html>', { pretendToBeVisual: true, url: "http://localhost" });
for (const key of ["window", "document", "HTMLElement", "Element", "SVGElement", "Node", "MutationObserver", "getComputedStyle"]) Object.defineProperty(globalThis, key, { value: key === "getComputedStyle" ? dom.window.getComputedStyle.bind(dom.window) : (dom.window as any)[key], configurable: true });
Object.assign(globalThis, { IS_REACT_ACT_ENVIRONMENT: true, requestAnimationFrame: dom.window.requestAnimationFrame.bind(dom.window), cancelAnimationFrame: dom.window.cancelAnimationFrame.bind(dom.window) });
dom.window.matchMedia = ((query: string) => ({ matches: false, media: query, addListener() {}, removeListener() {}, addEventListener() {}, removeEventListener() {} })) as any;
dom.window.HTMLElement.prototype.scrollIntoView = function() {};
dom.window.HTMLElement.prototype.getClientRects = function() { return [this.getBoundingClientRect()] as any; };
const React = await import("react");
const { createRoot } = await import("react-dom/client");
const { Modal, ModalLayer, ConfirmationDialog, useNotices } = await import("../src/ui");
const { modalStore } = await import("../src/modalStore");
const { beginFeedback } = await import("../src/feedback");
const { act, useState, StrictMode } = React;
const pause = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));
let controls: any;
let deletions = 0;
function Harness() {
  const [open, setOpen] = useState(true);
  const [confirm, setConfirm] = useState(false);
  const { Toasts } = useNotices();
  controls = { setOpen, setConfirm };
  return <><button>Abrir</button>{open && <Modal title="Editor" onClose={() => setOpen(false)}><button onClick={() => setConfirm(true)}>Eliminar registro</button>{confirm && <ConfirmationDialog title="¿Eliminar cliente?" description="Podrás recuperarlo desde Papelera." onClose={() => setConfirm(false)} onConfirm={() => { deletions++; setConfirm(false); }} />}</Modal>}{Toasts}</>;
}
const root = createRoot(document.getElementById("root")!);
await act(async () => { root.render(<StrictMode><Harness /><ModalLayer /></StrictMode>); });
assert.equal(modalStore.getSnapshot().length, 1);
await act(async () => { controls.setConfirm(true); });
assert.equal(modalStore.getSnapshot().length, 2);
assert.equal(deletions, 0);
await act(async () => { document.querySelector<HTMLButtonElement>(".confirmation-body + .modal-actions button")!.click(); });
assert.equal(deletions, 0);
assert.equal(modalStore.getSnapshot().length, 1);
assert.equal(document.querySelectorAll('.overlay [role="dialog"]').length, 2, "el modal permanece durante su animación de salida");
await act(async () => { await pause(450); });
assert.equal(document.querySelectorAll('.overlay [role="dialog"]').length, 1);
await act(async () => { controls.setConfirm(true); });
await act(async () => { document.querySelector<HTMLButtonElement>(".confirmation-submit")!.click(); });
assert.equal(deletions, 1, "solo confirma la eliminación al pulsar Sí, eliminar");
await act(async () => { await pause(450); });
await act(async () => { controls.setOpen(false); });
assert.equal(modalStore.getSnapshot().length, 0);
assert.equal(document.querySelectorAll('.overlay [role="dialog"]').length, 1);
await act(async () => { await pause(450); });
assert.equal(document.querySelectorAll('.overlay [role="dialog"]').length, 0);
let operation: ReturnType<typeof beginFeedback>;
await act(async () => { operation = beginFeedback("Guardando", "Guardando cliente"); });
assert.ok(document.querySelector(".feedback-card"));
await act(async () => { operation.success("Cliente guardado"); });
assert.match(document.querySelector(".feedback-card")!.textContent!, /Cliente guardado/);
await act(async () => { await pause(10200); });
await act(async () => { await pause(450); });
assert.equal(document.querySelector(".feedback-card"), null, "la alerta termina y sale tras 10 segundos");
assert.equal(document.body.style.overflow, "");
await act(async () => { root.unmount(); });
assert.equal(modalStore.getSnapshot().length, 0);
dom.window.close();
console.log("OK: montaje en StrictMode, confirmación, cancelación, salida animada y cierre automático de alerta a los 10 segundos.");
